/**
 * Calculates national arbitrage opportunity: compares local mandi price with highest-bidding national market
 */
export function getArbitrageSpread(
  cropName: string,
  localMandi: string,
  localPrice: number
): { highestMandi: string; highestPrice: number; netSpread: number } {
  const match = MANDI_RECORDS.find(
    (m) =>
      m.commodity.toLowerCase().includes(cropName.toLowerCase()) ||
      cropName.toLowerCase().includes(m.commodity.toLowerCase())
  );

  if (match && match.highestMandi && match.highestMandiPrice) {
    const netSpread = Math.max(0, match.highestMandiPrice - localPrice);
    return {
      highestMandi: match.highestMandi,
      highestPrice: match.highestMandiPrice,
      netSpread,
    };
  }

  // Calculated standard forward spread estimate
  const estimatedSpread = Math.round(localPrice * 0.055);
  return {
    highestMandi: 'National Terminal Market Hub',
    highestPrice: localPrice + estimatedSpread,
    netSpread: estimatedSpread,
  };
}

/**
 * Filter Mandi records by State and Category with fuzzy search support
 */
export function filterMarketPrices(
  prices: MarketPrice[],
  selectedState: string,
  selectedCategory: string,
  searchQuery = ''
): MarketPrice[] {
  let filtered = prices;

  if (selectedState && selectedState !== 'All States') {
    filtered = filtered.filter(
      (item) => item.state.toLowerCase() === selectedState.toLowerCase()
    );
  }

  if (selectedCategory && selectedCategory !== 'All') {
    filtered = filtered.filter(
      (item) => item.category.toLowerCase() === selectedCategory.toLowerCase()
    );
  }

  if (searchQuery.trim()) {
    const q = searchQuery.toLowerCase().trim();
    filtered = filtered.filter(
      (item) =>
        item.commodity.toLowerCase().includes(q) ||
        item.variety.toLowerCase().includes(q) ||
        item.market.toLowerCase().includes(q) ||
        item.district.toLowerCase().includes(q) ||
        item.state.toLowerCase().includes(q)
    );
  }

  return filtered;
}

export type MarketTimeRange = '1W' | '1M' | '3M' | '1Y' | 'All';

export interface HistoricalRangeSummary {
  points: {
    date: string;
    timestamp: number;
    modalPrice: number;
    minPrice: number;
    maxPrice: number;
    arrivalVolume: number;
  }[];
  currentPrice: number;
  startPrice: number;
  priceChange: number;
  percentChange: number;
  highPrice: number;
  lowPrice: number;
  avgVolume: number;
}

/** Returns observed history supplied by the live provider or the latest reference quote. */
export function generateHistoricalPriceData(
  crop: MarketPrice,
  range: MarketTimeRange = '1M'
): HistoricalRangeSummary {
  const days: Record<MarketTimeRange, number> = { '1W': 7, '1M': 30, '3M': 90, '1Y': 365, All: 3650 };
  const cutoff = Date.now() - days[range] * 86_400_000;
  const observed = (crop.history || []).filter((point) => point.timestamp >= cutoff).sort((a, b) => a.timestamp - b.timestamp);
  const points = observed.length > 0 ? observed : (crop.history || []).slice(-1).length > 0 ? (crop.history || []).slice(-1) : [{
    date: crop.arrivalDate || crop.updatedAt || 'Latest reference quote',
    timestamp: Date.parse(crop.arrivalDate || crop.updatedAt || '') || Date.now(),
    modalPrice: crop.modalPrice,
    minPrice: crop.minPrice,
    maxPrice: crop.maxPrice,
    arrivalVolume: 0,
  }];
  const startPrice = points[0]?.modalPrice || crop.modalPrice;
  const currentPrice = points.at(-1)?.modalPrice || crop.modalPrice;
  const priceChange = currentPrice - startPrice;
  const percentChange = Number(((priceChange / (startPrice || 1)) * 100).toFixed(2));
  const allPrices = points.map((p) => p.modalPrice);
  const highPrice = Math.max(...allPrices, crop.modalPrice);
  const lowPrice = Math.min(...allPrices, crop.modalPrice);
  const avgVolume = Math.round(points.reduce((acc, curr) => acc + curr.arrivalVolume, 0) / (points.length || 1));

  return {
    points,
    currentPrice,
    startPrice,
    priceChange,
    percentChange,
    highPrice,
    lowPrice,
    avgVolume,
  };
}

/**
 * Multi-Commodity & APMC Mandi Comparative Engine
 */
export function calculateCompareAnalytics(crops: MarketPrice[]) {
  if (!crops || crops.length === 0) return null;
  const groups = new Map<string, MarketPrice[]>();
  crops.forEach((crop) => {
    const key = [crop.commodity, crop.variety, crop.grade || '', crop.unit || '', crop.arrivalDate || ''].join('|').toLowerCase();
    groups.set(key, [...(groups.get(key) || []), crop]);
  });
  const compared = Array.from(groups.values()).sort((a, b) => b.length - a.length)[0] || [crops[0]];
  const comparable = compared.length >= 2;
  const prices = (comparable ? compared : [crops[0]]).map((c) => c.modalPrice);
  const maxPrice = Math.max(...prices);
  const minPrice = Math.min(...prices);
  const spreadDisparity = maxPrice - minPrice;

  // Transit/logistics standard deduction in India (approx ₹1.4/km/qtl for average 180 km inter-mandi haul)
  const estimatedAvgTransitDeduction = comparable ? 250 : 0;
  const netArbitragePotential = Math.max(0, spreadDisparity - estimatedAvgTransitDeduction);

  const comparedCrops = comparable ? compared : [crops[0]];
  const highestCrop = comparedCrops.find((c) => c.modalPrice === maxPrice) || comparedCrops[0];
  const lowestCrop = comparedCrops.find((c) => c.modalPrice === minPrice) || comparedCrops[comparedCrops.length - 1];

  return {
    highestCrop,
    lowestCrop,
    maxPrice,
    minPrice,
    spreadDisparity,
    estimatedTransitCost: estimatedAvgTransitDeduction,
    netArbitragePotential,
    bestReturnMandi: comparable ? highestCrop.market : 'Select the same commodity, variety, grade, and date',
    lowestReturnMandi: comparable ? lowestCrop.market : 'No comparable mandi pair',
    comparable,
    comparableCount: comparedCrops.length,
  };
}
